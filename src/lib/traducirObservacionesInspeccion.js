function normalizarFrase(texto) {
  return String(texto ?? "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[¿?¡!.,;:()[\]{}"]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function distanciaEdicion(a, b) {
  if (a === b) return 0;
  if (!a.length) return b.length;
  if (!b.length) return a.length;

  let anterior = Array.from({ length: b.length + 1 }, (_, i) => i);

  for (let i = 1; i <= a.length; i += 1) {
    const actual = [i];

    for (let j = 1; j <= b.length; j += 1) {
      const coste = a[i - 1] === b[j - 1] ? 0 : 1;
      actual[j] = Math.min(
        actual[j - 1] + 1,
        anterior[j] + 1,
        anterior[j - 1] + coste
      );
    }

    anterior = actual;
  }

  return anterior[b.length];
}

function buscarFraseConocida(texto) {
  const normalizada = normalizarFrase(texto);

  if (FRASES_INSPECCION_ES_EN[normalizada]) {
    return FRASES_INSPECCION_ES_EN[normalizada];
  }

  // La comparación aproximada solo se usa con frases largas y muy similares.
  // Evita forzar equivalencias dudosas en textos cortos.
  if (normalizada.length < 22) return null;

  let mejor = null;
  let mejorPuntuacion = 0;

  for (const [frase, traduccion] of Object.entries(
    FRASES_INSPECCION_ES_EN
  )) {
    if (Math.abs(frase.length - normalizada.length) > 3) continue;

    const distancia = distanciaEdicion(normalizada, frase);
    const puntuacion =
      1 - distancia / Math.max(normalizada.length, frase.length);

    if (puntuacion > mejorPuntuacion) {
      mejor = traduccion;
      mejorPuntuacion = puntuacion;
    }
  }

  return mejorPuntuacion >= 0.94 ? mejor : null;
}

/**
 * Traduce observaciones conocidas de inspecciones al inglés.
 *
 * - Si el idioma del cliente no es inglés, devuelve el texto original.
 * - No modifica ni guarda el texto en la base de datos.
 * - Si no reconoce una frase con suficiente seguridad, conserva el original.
 */
export function traducirObservacionInspeccion(texto, idiomaCliente = "es") {
  if (typeof texto !== "string" || !texto.trim()) return texto ?? "";
  if (idiomaCliente !== "en") return texto;

  const original = texto;
  const directa = buscarFraseConocida(original);

  if (directa) return directa;

  // Prueba fragmentos separados por saltos de línea o puntuación.
  // Cada fragmento desconocido se conserva sin alteraciones.
  const partes = original.split(/(\n+|(?<=[.;])\s+)/);

  if (partes.length > 1) {
    return partes
      .map((parte) => {
        if (!parte.trim() || /^[\n\s.;]+$/.test(parte)) return parte;
        return buscarFraseConocida(parte) || parte;
      })
      .join("");
  }

  return original;
}

export default traducirObservacionInspeccion;
